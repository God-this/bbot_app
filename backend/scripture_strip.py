"""평가용 — 답변에서 성경 인용 부분을 제거한다.

RAGAS faithfulness는 답변을 statement 단위로 분해해 "검색 문서(web/book/video)에서
추론 가능한가"를 판정한다. 성경 구절은 성경 DB에서 온 것이라 창조과학 검색 문서에는
없고, 따라서 **정확한 인용이어도 0점**을 받는다.

시스템 프롬프트가 답변 말미에 구절 인용/묵상을 요구하므로(bbot_graph.py
SYSTEM_PROMPT_TEMPLATE "4. 마무리"), 실서비스 형태 답변은 구조적으로 점수가 깎인다.
실측: 근거가 충분한 답변도 faithfulness 0.33 / composite 0.476 → would_delete.

그래서 **평가에 넣기 직전에만** 구절을 떼어낸다.
사용자 응답과 캐시에는 손대지 않는다 — 여기서 만든 문자열은 qa_eval_queue로만 간다.

인용 형식은 bible_tool.BIBLE_TOOL_PROMPT가 강제한다:
    "본문" (요한복음 3:16, 개역한글)
"""

import re

from logging_config import get_logger

logger = get_logger(__name__)

# bible_tool.BOOKS의 정식 명칭 66권. 약어(창/요 등)는 인용 형식에 쓰이지 않지만
# 모델이 섞어 쓸 수 있으므로 함께 받는다.
_BOOK_NAMES = [
    "창세기", "출애굽기", "레위기", "민수기", "신명기", "여호수아", "사사기", "룻기",
    "사무엘상", "사무엘하", "열왕기상", "열왕기하", "역대상", "역대하", "에스라",
    "느헤미야", "에스더", "욥기", "시편", "잠언", "전도서", "아가", "이사야",
    "예레미야애가", "예레미야", "에스겔", "다니엘", "호세아", "요엘", "아모스",
    "오바댜", "요나", "미가", "나훔", "하박국", "스바냐", "학개", "스가랴", "말라기",
    "마태복음", "마가복음", "누가복음", "요한복음", "사도행전", "로마서",
    "고린도전서", "고린도후서", "갈라디아서", "에베소서", "빌립보서", "골로새서",
    "데살로니가전서", "데살로니가후서", "디모데전서", "디모데후서", "디도서",
    "빌레몬서", "히브리서", "야고보서", "베드로전서", "베드로후서",
    "요한일서", "요한이서", "요한삼서", "유다서", "요한계시록",
]
# '예레미야애가'가 '예레미야'보다 먼저 와야 부분 매칭되지 않는다.
_BOOK_ALT = "|".join(sorted(_BOOK_NAMES, key=len, reverse=True))

# 여는/닫는 따옴표 변형을 모두 받는다 (모델이 " " " 「 』 등을 섞어 씀).
_OPEN = r'["“「『‘]'
_CLOSE = r'["”」』’]'

# 1) 인용문 + 출처: "본문" (요한복음 3:16, 개역한글)
#    출처 표기의 '개역한글'은 선택으로 둔다(모델이 생략하는 경우가 있음).
_QUOTED_CITATION = re.compile(
    rf'{_OPEN}[^"“”「」『』]{{1,500}}?{_CLOSE}\s*'
    rf'\(\s*(?:{_BOOK_ALT})\s*\d+\s*[:：]\s*\d+(?:\s*[-~]\s*\d+)?'
    rf'(?:\s*,\s*[^)]{{1,20}})?\s*\)',
    re.DOTALL,
)

# 2) 출처만 남은 경우: (창세기 1:24, 개역한글) / (요한복음 3:16)
_CITATION_ONLY = re.compile(
    rf'\(\s*(?:{_BOOK_ALT})\s*\d+\s*[:：]\s*\d+(?:\s*[-~]\s*\d+)?'
    rf'(?:\s*,\s*[^)]{{1,20}})?\s*\)'
)

# 3) 괄호 없이 문장에 녹은 장절 언급: "창세기 1장 24절은 ...", "요한복음 3:16에서"
#    장절 표기만 지우면 "...보여줍니다. 은 하나님이..." 처럼 조사가 남아
#    비문이 되고, judge가 그 조각을 근거 없는 statement로 읽는다.
#    그래서 장절이 포함된 **문장 전체**를 지운다.
#    장절 표기 변형을 모두 받는다 (실측에서 아래 두 형태가 새어나갔다):
#      "창세기 5장과 11장"      — 절 없이 장만
#      "창세기 1장 6-8절"       — 절 범위
#      "요한복음 3:16"          — 콜론형
_VERSE_PART = r'(?:장(?:\s*\d+\s*(?:[-~]\s*\d+\s*)?절)?|[:：]\s*\d+(?:\s*[-~]\s*\d+)?)'
_INLINE_REF_SENTENCE = re.compile(
    rf'[^.!?\n]*(?:{_BOOK_ALT})\s*\d+\s*{_VERSE_PART}[^.!?\n]*[.!?]?'
)


# 4) 묵상 권유 문구.
#    시스템 프롬프트 "4. 마무리"는 구절 인용 **또는** 묵상 문구를 요구한다
#    (either/or). 묵상 문구에는 장절이 없어 위 정규식들이 잡지 못하는데,
#    이 역시 검색 문서에 없는 내용이라 faithfulness가 0점을 준다.
#    실측: 구절을 떼어내도 이 문장 때문에 0.5에 머물렀다.
#    권유형 종결("~보시기 바랍니다", "~해 봅시다")과 묵상 어휘가 함께 오는
#    마지막 문장만 지운다. 본문 중간의 설명 문장은 건드리지 않는다.
_DEVOTIONAL_WORDS = r"묵상|섭리|신비|경외|찬양|은혜|감사|기도|믿음|말씀"
_DEVOTIONAL_TAIL = re.compile(
    rf'[^.!?\n]*(?:{_DEVOTIONAL_WORDS})[^.!?\n]*'
    rf'(?:바랍니다|바랍니다\.|봅시다|보십시오|하십시오|합시다|바라며|되시기|기를)'
    rf'[^.!?\n]*[.!?]?\s*$'
)


def strip_scripture(answer: str) -> str:
    """답변에서 성경 인용과 묵상 마무리를 제거한 '본문만' 문자열을 반환.

    원문을 수정하지 않는다 — 평가 입력용 사본을 만들 뿐이다.
    제거 후 빈 문자열이 되면(구절만으로 이루어진 답변) 원문을 그대로 돌려준다.
    평가할 게 없다고 빈 문자열을 넘기면 RAGAS가 엉뚱한 점수를 내기 때문이다.
    """
    if not answer:
        return answer

    text = _QUOTED_CITATION.sub(" ", answer)
    text = _CITATION_ONLY.sub(" ", text)
    text = _INLINE_REF_SENTENCE.sub(" ", text)
    # 묵상 문구는 마지막 문장에만 적용한다(본문 설명 보존).
    text = _DEVOTIONAL_TAIL.sub(" ", text.rstrip())

    # 구절을 마크다운으로 강조한 경우(**"..." (창세기 1:1)**) 바깥쪽 ** 가 남아
    # "** **" 같은 빈 강조가 생긴다. 실측에서 발생했다.
    # 같은 기호가 짝으로 붙고 사이에 내용이 없을 때만 지운다.
    # (**중요한** 처럼 내용이 있는 강조는 건드리지 않는다)
    text = re.sub(r"(?<![*_])(\*{2,3}|_{2,3})[ \t]*\1(?![*_])", " ", text)
    # 구절을 유도하던 문장도 함께 지운다 — 구절이 사라지면 "말씀을 드리면:"
    # 같은 꼬리만 남아 평가 입력이 끊긴 문장이 된다.
    text = re.sub(
        r"(?m)^[^\n]{0,80}(?:말씀|구절|성구)[^\n]{0,40}(?:드리면|나눕니다|소개합니다|인용하면)\s*[:：]?\s*$",
        "", text,
    )

    # 인용을 들어내고 남은 공백/빈 줄 정리
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    # 구절만 있던 줄이 구두점/기호 찌꺼기로 남는 경우 정리
    text = re.sub(r"(?m)^[\s.,·…\-—:：*_]*$\n?", "", text)
    text = text.strip()
    # 문장 끝에 남은 유도 구두점 정리 ("...드리면:" 류)
    text = re.sub(r"[\s:：*_]+$", "", text)

    if not text:
        logger.debug("구절 제거 후 본문이 비어 원문을 사용한다")
        return answer.strip()

    return text
